入口 开始

段 代码
开始:
    装 甲, 10          ; 甲 = 10            B8 0A 00 00 00
    装 乙, 5           ; 乙 = 5             B9 05 00 00 00
    加 甲, 乙          ; 甲 = 甲 + 乙       03 C1
    自增 甲            ; 甲 = 甲 + 1        40
    装 丙, 甲          ; 丙 = 甲            89 C2

    压 甲              ; 50
    弹 丁              ; 5B
    比 甲, 丙          ; 3B C2

    等跳 相等          ; 0F 84 rel32
    跳 结束            ; E9 rel32

相等:
    ; 取字符串变量的地址，再读它的首字节（长度前缀）
    装 丁, 问候        ; BB + addr32
    装 丙, [丁]        ; 8B 53 00

结束:
    系调 4Ch           ; B4 4C CD 21（DOS 退出）
    停                 ; F4

段 数据
整数 计数 = 7
字符 字母 = 'A'
字串 问候 = "你好，世界"